-- The application uses WorkOS sessions, so its DB role is server-only. Keep
-- this explicit so a later Supabase client/RLS rollout cannot accidentally
-- expose all rows to an anon key.
alter table public.users enable row level security;
alter table public.courses enable row level security;
alter table public.review_cards enable row level security;
alter table public.counter_snapshots enable row level security;

create or replace function public.refresh_counter_snapshots(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.counter_snapshots where user_id = p_user_id;

  insert into public.counter_snapshots (user_id, course_id, total_lines, learned_lines, due_lines, new_lines, computed_at)
  select
    p_user_id,
    c.id,
    count(m.id)::integer,
    count(rc.id) filter (where rc.last_review is not null or rc.state <> 0)::integer,
    count(rc.id) filter (where rc.due <= now() and (rc.last_review is not null or rc.state <> 0))::integer,
    (count(m.id) - count(rc.id) filter (where rc.last_review is not null or rc.state <> 0))::integer,
    now()
  from public.courses c
  join public.chapters ch on ch.course_id = c.id
  join public.moves m on m.chapter_id = ch.id and m.move_type = 'repertoire'
  left join public.review_cards rc on rc.move_id = m.id and rc.user_id = p_user_id
  where c.user_id = p_user_id
  group by c.id;

  insert into public.counter_snapshots (user_id, course_id, total_lines, learned_lines, due_lines, new_lines, computed_at)
  select
    p_user_id,
    null,
    coalesce(sum(total_lines), 0)::integer,
    coalesce(sum(learned_lines), 0)::integer,
    coalesce(sum(due_lines), 0)::integer,
    coalesce(sum(new_lines), 0)::integer,
    now()
  from public.counter_snapshots
  where user_id = p_user_id and course_id is not null;
end;
$$;
