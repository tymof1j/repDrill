-- RepDrill's Supabase target schema.
--
-- WorkOS is the identity provider.  `users.id` is RepDrill's internal UUID;
-- `workos_user_id` is the stable external identity and `legacy_convex_id`
-- keeps the Convex -> Supabase migration resumable and auditable.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  workos_user_id text unique,
  legacy_convex_id text unique,
  name text,
  image text,
  email text,
  email_verification_time timestamptz,
  phone text,
  phone_verification_time timestamptz,
  is_anonymous boolean not null default false,
  lichess_username text,
  chesscom_username text,
  language text not null default 'en' check (language in ('en', 'uk')),
  last_analyze_sync_lichess_at timestamptz,
  last_analyze_sync_chesscom_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists users_email_lower_idx on public.users (lower(email)) where email is not null;

-- Convex's internal auth tables contain provider/session records which cannot
-- be imported as WorkOS credentials. Preserve them as immutable JSON so the
-- migration is lossless and auditable, while WorkOS owns future sessions.
create table if not exists public.legacy_auth_documents (
  id bigint generated by default as identity primary key,
  source_table text not null,
  source_id text not null,
  payload jsonb not null,
  imported_at timestamptz not null default now(),
  unique (source_table, source_id)
);

create table if not exists public.legacy_id_map (
  source_table text not null,
  source_id text not null,
  destination_id uuid not null,
  migrated_at timestamptz not null default now(),
  primary key (source_table, source_id)
);

create table if not exists public.legacy_storage_documents (
